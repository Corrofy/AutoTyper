#!/usr/bin/env node
/**
 * build.mjs — assemble the two browser packages from one source tree.
 *
 * Why a build step at all?
 *   Chromium MV3 runs the background as a service worker; Firefox MV3 runs it as
 *   a non-persistent event page with a *list* of scripts. The two manifests are
 *   therefore genuinely different, but every other file is identical.
 *
 * Why no bundler?
 *   The shipped code is classic scripts sharing one `AutoTyper` namespace, so
 *   nothing needs bundling. Keeping this file dependency-free means `node
 *   build.mjs` works on a fresh machine with no `npm install`.
 *
 * Usage:
 *   node build.mjs            # dist/chromium, dist/firefox, two zips
 *   node build.mjs --no-zip   # skip archives (faster during development)
 *   node build.mjs --dev      # prepend the dev bridge flag (e2e harness only)
 */

import { cp, mkdir, readFile, readdir, rm, stat, writeFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(fileURLToPath(import.meta.url));
const SRC = join(ROOT, "src");
const DIST = join(ROOT, "dist");

const SKIP_FROM_BUILD = new Set(["manifest.base.json"]);

/** Content scripts are shared by both builds and must stay in this order. */
const CONTENT_SCRIPT_ORDER = [
  "shared/protocol.js",
  "background/settings.js",
  // Pure engine modules. They have no dependencies beyond the namespace, but
  // they load before the UI so content.js can rely on them (M2 onward).
  "content/engine/cadence.js",
  "content/engine/mistakes.js",
  "content/engine/keycode-map.js",
  "content/hotkeys.js",
  "content/injection/dispatcher.js",
  "content/injection/adapters/textarea.js",
  "content/injection/detect.js",
  "content/engine/runner.js",
  "content/focus-tracker.js",
  "content/overlay/overlay.js",
  "content/content.js",
];

const TARGETS = {
  chromium: (base) => ({
    ...base,
    // Chrome 121+ ignores background.scripts in MV3, but we emit a clean
    // manifest anyway so there is nothing to misinterpret.
    minimum_chrome_version: "121",
    background: {
      service_worker: "background/background.js",
    },
  }),
  firefox: (base) => ({
    ...base,
    background: {
      scripts: [
        "shared/protocol.js",
        "background/settings.js",
        "background/background.js",
      ],
    },
    browser_specific_settings: {
      gecko: {
        // Keep a stable id so an unlisted AMO signing pass stays possible later,
        // even though v1 ships as a temporary add-on only.
        id: "auto-typer@dev.local",
        strict_min_version: "128.0",
        // Required by AMO for new submissions from Firefox 140 onward. The
        // extension makes no network requests and collects nothing.
        data_collection_permissions: { required: ["none"] },
      },
    },
  }),
};

async function walk(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(full)));
    else out.push(full);
  }
  return out;
}

/** Generated only with --dev; never listed by a production manifest. */
const DEV_FLAG_FILE = "shared/dev-flags.js";
const DEV_FLAG_SOURCE = `// Generated by \`node build.mjs --dev\`. A production build has no such file.
(function (global) {
  "use strict";
  const AT = (global.AutoTyper = global.AutoTyper || {});
  AT.devTools = true;
})(globalThis);
`;

async function copySource(targetDir) {
  const files = await walk(SRC);
  let copied = 0;
  for (const file of files) {
    const rel = relative(SRC, file).split("\\").join("/");
    if (SKIP_FROM_BUILD.has(rel)) continue;
    const dest = join(targetDir, rel);
    await mkdir(dirname(dest), { recursive: true });
    await cp(file, dest);
    copied += 1;
  }
  return copied;
}

/** Fail the build if the manifest points at a file that does not exist. */
async function assertReferences(targetDir, manifest) {
  const refs = [manifest.background?.service_worker, ...(manifest.background?.scripts ?? []), manifest.action?.default_popup, ...Object.values(manifest.action?.default_icon ?? {}), ...Object.values(manifest.icons ?? {}), ...(manifest.content_scripts ?? []).flatMap((cs) => cs.js ?? [])].filter(Boolean);

  const missing = [];
  for (const ref of refs) {
    try {
      await stat(join(targetDir, ref));
    } catch {
      missing.push(ref);
    }
  }
  if (missing.length) {
    throw new Error(`manifest references missing files: ${missing.join(", ")}`);
  }
}

async function zip(targetDir, zipPath) {
  await rm(zipPath, { force: true });
  const result = spawnSync("zip", ["-qr", zipPath, "."], { cwd: targetDir });
  if (result.status !== 0) {
    throw new Error(`zip failed (${result.status}): ${result.stderr?.toString() ?? ""}`);
  }
}

async function main() {
  const noZip = process.argv.includes("--no-zip");
  const dev = process.argv.includes("--dev");
  const base = JSON.parse(await readFile(join(SRC, "manifest.base.json"), "utf8"));

  // Guard: the two manifests must agree with the content-script order the
  // content world actually relies on.
  const declared = base.content_scripts?.[0]?.js ?? [];
  if (declared.join() !== CONTENT_SCRIPT_ORDER.join()) {
    throw new Error(
      `content script order drifted from build.mjs\n  manifest: ${declared.join(", ")}\n  build:    ${CONTENT_SCRIPT_ORDER.join(", ")}`,
    );
  }

  await rm(DIST, { recursive: true, force: true });

  const rows = [];
  for (const [name, transform] of Object.entries(TARGETS)) {
    const outDir = join(DIST, name);
    await mkdir(outDir, { recursive: true });
    const copied = await copySource(outDir);
    const manifest = transform(base);
    if (dev) {
      // A code flag, not a manifest key: Firefox drops unknown top-level manifest
      // properties before `runtime.getManifest()` can see them, so a dev_tools
      // key is not a reliable gate in the content world. The generated script is
      // loaded first and sets AT.devTools in the isolated world; production
      // builds contain neither the file nor the manifest entry.
      await mkdir(join(outDir, "shared"), { recursive: true });
      await writeFile(join(outDir, DEV_FLAG_FILE), DEV_FLAG_SOURCE);
      manifest.content_scripts[0].js.unshift(DEV_FLAG_FILE);
    }
    await assertReferences(outDir, manifest);
    await writeFile(join(outDir, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);

    let zipNote = "skipped";
    if (!noZip) {
      const zipPath = join(DIST, `auto-typer-${name}.zip`);
      await zip(outDir, zipPath);
      zipNote = `${(await stat(zipPath)).size.toLocaleString()} B zip`;
    }
    rows.push({
      target: name,
      files: copied + 1 + (dev ? 1 : 0),
      out: relative(ROOT, outDir),
      packaged: zipNote,
    });
  }

  console.log("Auto Typer build" + (dev ? " (dev bridge enabled)" : ""));
  for (const row of rows) {
    console.log(`  ${row.target.padEnd(9)} ${String(row.files).padStart(3)} files  ${row.out}  ${row.packaged}`);
  }
  console.log("\nLoad it:");
  console.log("  Chromium: chrome://extensions → Developer mode → Load unpacked → dist/chromium");
  console.log("  Firefox:  about:debugging#/runtime/this-firefox → Load Temporary Add-on → dist/firefox/manifest.json");
}

main().catch((err) => {
  console.error(`build failed: ${err.message}`);
  process.exit(1);
});
